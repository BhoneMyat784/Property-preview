const Context = createContext<{
  locale: "my" | "en";
  setLocale: (v: "my" | "en") => void;
  t: (key: Key) => string;
}>({ locale: "my", setLocale: () => {}, t: (k) => my[k] });
export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, set] = useState<"my" | "en">("my");
  useEffect(() => {
    AsyncStorage.getItem("portal-language")
      .then((v) => {
        if (v === "en" || v === "my") set(v);
      })
      .catch(() => {});
  }, []);
  function setLocale(v: "my" | "en") {
    set(v);
    void AsyncStorage.setItem("portal-language", v).catch(() => {});
  }
  return (
    <Context.Provider
      value={{ locale, setLocale, t: (k) => (locale === "my" ? my : en)[k] }}
    >
      {children}
    </Context.Provider>
  );
}
export const useLanguage = () => useContext(Context);
